def build_compress_user_prompt(current_prompt: str, target_chars: int) -> str:
    """User-prompt для SeedanceCompressThread.

    Возвращает текст вида:
        ТЕКУЩИЙ ПРОМПТ (XXXX знаков):
        <current_prompt>
        ═══...
        ЗАДАЧА: сократи этот промпт до YYYY знаков.
        ═══...

    target_chars подставляется и в SYSTEM_COMPRESS (через .format в
    thread'е), и в user prompt (здесь) — чтобы Opus видел цель сразу
    в двух местах.
    """
    current_len = len(current_prompt or "")
    return (
        f"ТЕКУЩИЙ ПРОМПТ ({current_len} знаков):\n"
        f"\n"
        f"{current_prompt}\n"
        f"\n"
        f"═══════════════════════════════════════════\n"
        f"ЗАДАЧА: сократи этот промпт до {target_chars} знаков.\n"
        f"═══════════════════════════════════════════\n"
    )
