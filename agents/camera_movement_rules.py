# -*- coding: utf-8 -*-
"""
agents/camera_movement_rules.py — единый источник правил движения камеры
для Seedance Writer.

Зачем отдельный модуль:
  • Все правила динамического движения камеры (运镜) живут в одном месте.
  • Агент Seedance (agents/seedance_prompts.py) тянет CAMERA_MOVEMENT_RULES
    отсюда и врезает в SYSTEM через .replace по плейсхолдеру
    «〈CAMERA_MOVEMENT_RULES〉».
  • Compress (SYSTEM_COMPRESS) использует CAMERA_BLOCK_HEADER в 12-м пункте
    нерушимого списка — блок 运镜 и маркеры переходов между шотами не режутся.
  • Будущая правка правил движения = правка ТОЛЬКО этого файла.

Лист-модуль: сам никого из приложения не импортирует → не создаёт
циклических импортов. PyInstaller подхватывает его статически через
`from agents.camera_movement_rules import …` в seedance_prompts.py.

Замена дефолтного handheld: раньше agents/seedance_prompts.py:63 жёстко
вшивал 手持纪录片风格 (handheld documentary style) во ВСЕ промпты Seedance.
Теперь handheld — лишь один из вариантов движения, привязанный к погоням/
дракам/панике/бегству; по умолчанию движение выбирается по содержанию шота.

История: создан 2026-06-19 (фича «динамическое движение камеры Seedance»).
"""

from __future__ import annotations


# Заголовок пер-шот секции движения камеры в ВЫХОДНОМ промпте (sentinel).
# Тот же стиль, что у существующих 镜头：/动作：/技术参数：. Используется:
#   • в шаблоне SYSTEM (формат выхода) — Opus эмитит эту секцию;
#   • в 12-м пункте SYSTEM_COMPRESS — compress защищает её по имени.
CAMERA_BLOCK_HEADER = "运镜："

# 4 типа межшотового перехода (префиксы маркеров; после «—» идёт обоснование).
TRANSITION_MARKERS = [
    "[HARD CUT",
    "[MATCH CUT",
    "[CONTINUOUS CAMERA MOVE",
    "[CONTINUOUS HANDHELD",
]

# Полный манифест того, что SYSTEM_COMPRESS не режет (см. п.12 нерушимого
# списка): заголовок 运镜 + все маркеры переходов. Ссылается из 12-го пункта
# текстово; задел под возможную программную проверку компрессии.
PROTECT_MARKERS = [CAMERA_BLOCK_HEADER, *TRANSITION_MARKERS]


# Полный методический блок-инструкция для Opus. Врезается в SYSTEM агента
# Seedance через .replace("〈CAMERA_MOVEMENT_RULES〉", CAMERA_MOVEMENT_RULES).
# Формат — русская методика + китайские формулировки 运镜 (как в остальном
# SYSTEM: режиссура объясняется по-русски, на выход идут китайские строки).
CAMERA_MOVEMENT_RULES = """\
═══════════════════════════════════════════════════════════════════════
РЕЖИССУРА ДВИЖЕНИЯ КАМЕРЫ (运镜) — ОБЯЗАТЕЛЬНО В КАЖДОМ ШОТЕ
═══════════════════════════════════════════════════════════════════════

ГЛАВНЫЙ ПРИНЦИП:
- Полной статики в кадре не бывает. Минимум — микро-дыхание камеры 1-2%.
- По умолчанию — осознанное движение ПО СОДЕРЖАНИЮ шота, НЕ дефолтный handheld.
- author_camera ВСЕГДА главнее правил ниже. Если в шоте задан author_camera
  (авторский ракурс/движение из сценария) — строка 运镜 следует ему, правила
  ЧАСТЕЙ 1-3 уступают. Даже при author_camera = «статика» сохраняется
  минимальное дыхание камеры 1-2%.

В каждом шоте ПОСЛЕ блока 镜头 добавляй короткую строку 运镜： — китайская
формулировка движения + амплитуда + тайминг старта/стопа. Пример:
    运镜：极缓推进，5-10%幅度，1秒后启动，结束前0.5秒停止。

───────────────────────────────────────────────────────────────────────
ЧАСТЬ 1 — ДВИЖЕНИЕ ВНУТРИ ШОТА (выбери строку по содержанию кадра)
───────────────────────────────────────────────────────────────────────
- Диалог 2+ персонажей в одном кадре        → 缓慢环绕，人物保持画面中心
- Крупный план персонажа во время реплики   → 极缓推进，5-10%幅度
- Крупный план: финал сцены / осознание     → 极缓拉远
- Крупный план статичного объекта           → 缓慢推进至物体
  (портрет, документ, фото)
- Действие персонажа с объектом             → 轻微横移跟随动作
- Шот без людей (интерьер, деталь среды)     → 缓慢上摇 / 下摇 / 横移
- Wide shot локации (установочный кадр)      → 缓慢推进 / 轻微横移
- Погоня, драка, паника, бегство            → 手持跟随，紧张呼吸
- Скрытое наблюдение, угроза                 → 缓慢跟拍，侧后方
- Эмоциональная статичная сцена             → 镜头微微呼吸，几乎不动
  (тишина после ссоры, ожидание)

ОБЩИЕ ПРАВИЛА ДВИЖЕНИЯ:
- Амплитуда 3-15% за весь шот.
- 手持 (handheld) — ТОЛЬКО для драк/погонь/паники/бегства. НИКОГДА для
  разговоров и крупных планов.
- Пауза 1-1.5 сек статики перед началом движения (камера стартует не сразу).
- Если за шотом идёт [HARD CUT] — движение ОСТАНАВЛИВАЕТСЯ за 0.5 сек до
  конца шота. В строке 运镜 пиши «结束前0.5秒停止».

───────────────────────────────────────────────────────────────────────
ЧАСТЬ 2 — ПЕРЕХОД МЕЖДУ ШОТАМИ (дефолта НЕТ — выбери ОДИН тип и обоснуй)
───────────────────────────────────────────────────────────────────────
Перед каждым шотом ставь маркер перехода с обоснованием в квадратных скобках:
    [HARD CUT — обоснование]
    [MATCH CUT — обоснование]
    [CONTINUOUS CAMERA MOVE — обоснование]
    [CONTINUOUS HANDHELD — обоснование]

[HARD CUT] — резкая склейка.
  Когда: shot-counter-shot диалог, резкая смена эмоции, реакция-кадр,
  разные углы без визуальной связи.
  Требования: шот ПЕРЕД cut'ом кончается стабильной камерой (движение
  остановлено за 0.5 сек до конца); шот ПОСЛЕ — стартует паузой 1-1.5 сек.

[MATCH CUT] — склейка по похожей композиции.
  Когда: от персонажа к объекту в его руке, от взгляда — к тому на что
  смотрят, от детали — к похожей детали.
  Требования: финал шота А = похожая композиция с началом шота Б; указать
  это в 运镜 ОБОИХ шотов.

[CONTINUOUS CAMERA MOVE] — плавный непрерывный переход БЕЗ handheld.
  Когда: камера отъезжает от лица и поворачивается к объекту; от широкого
  плана к детали наездом; два соседних шота — одна непрерывная мысль.
  Требования: штативный/dolly ход (не дрожащий); движение конца шота А =
  логичное начало шота Б; в 运镜 обоих указать «镜头运动延续» (продолжение
  движения).

[CONTINUOUS HANDHELD] — непрерывный handheld дубль.
  Когда: ТОЛЬКО погоня, драка, паника, бегство, активное физ. движение.
  Требования: весь блок — одна непрерывная сцена без cut'ов.

───────────────────────────────────────────────────────────────────────
ЧАСТЬ 3 — РЕЖИССЁРСКИЕ ПРИЁМЫ (применяй по ситуации)
───────────────────────────────────────────────────────────────────────
1.  ОДИН ШОТ НЕСЁТ ОСНОВНОЕ ДВИЖЕНИЕ. В блоке из 4 шотов активное движение
    только у ОДНОГО шота, остальные тише (微呼吸 или почти статика). Всегда.
2.  МЕДЛЕННЕЕ ЧЕМ КАЖЕТСЯ. Амплитуда 3-8% вместо 10-15% — для драм. сцен,
    диалогов, крупных планов.
3.  ОБРАТНОЕ ДВИЖЕНИЕ ДЛЯ КОНТРАСТА. Паника → камера ОТЪЕЗЖАЕТ; спокойный
    диалог → камера НАЕЗЖАЕТ. На ключевых эмоциональных моментах.
4.  ВЫСОТА КАМЕРЫ И ЕЁ СМЕНА. Низкая точка + подъём = «герой растёт»;
    высокая + опускание = «падает». В сценах конфликта/конфронтации.
5.  ДЫХАНИЕ КАМЕРЫ В СТАТИКЕ. Микро-сдвиг 1-2% на штативе. Для эмоц.
    статичных моментов. ВСЕГДА при author_camera = статика.
6.  ASYMMETRIC FRAMING. Персонаж смещён, камера наклонена 2-5°. Для
    внутреннего конфликта/обмана/скрытой угрозы. В Seedance — строкой
    «保持分镜中的非对称构图» (удерживай асимметрию из сториборда).
7.  ПУСТОЕ ПРОСТРАНСТВО КАК ПРИЁМ. Персонаж в углу, 70% пустоты; камера
    сдвигается так, чтобы пустое стало ещё больше. Для одиночества/потери/разрыва.
8.  НЕОБЪЯСНИМОЕ ДВИЖЕНИЕ. Камера движется без явной причины. Для ключевых
    моментов раскрытия информации / сюжетного поворота.
9.  СВЕТ + КАМЕРА. Холодный жёсткий свет → амплитуда 3-5%; тёплый размытый
    → 5-10%; контрсвет/силуэт → 1-3%. Всегда сверяй с типом света из 技术参数.
10. ПАУЗА ПЕРЕД ДВИЖЕНИЕМ. Первые 1-1.5 сек — статика, потом старт. ВСЕГДА
    для шотов 4+ сек. В 运镜: «1秒后启动» / «1.5秒后启动».

ВЗАИМОДЕЙСТВИЕ С author_camera (приоритет):
- author_camera задан → 运镜 СЛЕДУЕТ авторскому ракурсу/движению; ЧАСТИ 1-3
  уступают; минимальное дыхание 1-2% сохраняется всегда.
- author_camera пуст → выбирай движение по ЧАСТИ 1 + приёмам ЧАСТИ 3.\
"""
